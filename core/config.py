FACE_EDGE_MARGIN = 0.03  # 框中心离画布边缘至少这么远

# 输入平滑：用**时间常数**而不是"每帧系数"。
# 每帧系数（旧写法 SMOOTH=0.35）的问题：摄像头帧率一变，实际跟随速度就变 ——
# 30fps 下相当于 95ms 时间常数，掉到 15fps 就变成 190ms，手感明显发钝。
# 改成 k = 1 - exp(-dt/tau) 之后，无论帧率如何，跟随速度都一致。
HEAD_TAU = 0.075         # 头部跟随时间常数（秒），越小越跟手
HAND_TAU = 0.055         # 手部跟随时间常数
BODY_TAU = 0.110         # 全身横移的时间常数（身体比头重，稍慢更自然）

# =========================================================================== #
# 手部映射
# =========================================================================== #
HAND_ENABLE = True
HAND_MAX_NUM = 2         # 最多同时跟踪的手数
# 手部检测降频：肤色分割 + 距离变换 + 凸包缺陷一套下来比人脸检测贵得多，
# 而手部动作的带宽远低于 30Hz，隔帧跑完全够用，还能把手感让给头部。
HAND_EVERY = 2           # 每 N 帧跑一次手部检测（1 = 每帧）
HAND_DEADZONE = 0.012    # 掌心位置死区
HAND_OPEN_THRESHOLD = 0.62   # 张合度高于此 → 判定为"张开"
HAND_CLOSE_THRESHOLD = 0.34  # 低于此 → 判定为"握拳"
HAND_PINCH_THRESHOLD = 0.34  # 拇指-食指距离 / 掌宽，低于此 → 捏合
HAND_LOST_AFTER = 0.6        # 多久没检测到手就认为"手离开"

# =========================================================================== #
# 识别状态与失检处理（这是"没识别到头时别乱动"的核心参数）
# =========================================================================== #
# 单帧漏检非常常见：转头、眨眼间的遮挡、曝光突变、模型抖动。
# 如果直接把"这一帧没检测到"当成丢失，控制量会在每帧之间反复重启/停住，
# 表现出来就是**角色自己在乱动**。所以丢失必须是一个**带迟滞的状态**：
#
#   TRACKING  正常识别
#   HOLD      连续丢检 ≤ HOLD_AFTER：**冻结**上一次的有效输出（一点不变）
#   LOST      超过 HOLD_AFTER：轴量立即归零、动作键立即清零（不做缓慢衰减）
#
# 注意 HOLD 阶段绝不能用"衰减到 0"：那样每次漏检角色都会往中间滑一下，
# 下一帧检测回来又弹回去 —— 这正是抖动的来源。
HOLD_AFTER = 0.15        # 连续丢检不超过这个时长 → 冻结输出（约 4~5 帧 @30fps）
REACQ_STEP = 0.62        # 重新捕获那一帧，横向量的最大变化量（防假阳性把角色甩到一边）

