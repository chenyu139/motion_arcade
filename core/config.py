# 全身骨骼 + 手部 21 点的检测频率（每 N 帧一次）。
# 头部控制由 YuNet 每帧保证实时性，而身体动作的带宽远低于 30Hz，
# 隔帧跑既能省一半开销，又不会让动作有可感知的延迟。
VISION_EVERY = 2

# 视觉帧新鲜度上限：超过这个时间没有重新推理，get_vision() 按"没有检测到"返回。
# 退避最长拉到 1/12 帧（约 0.4s），但退避只发生在"上一次就没检测到"之后，
# 所以 0.35s 对合法的保持不会误伤。
VISION_STALE_AFTER = 0.35

# =========================================================================== #
# 头部映射
# =========================================================================== #
CALIB_FRAMES = 24        # 校准采样帧数
DEADZONE_X = 0.06        # 水平死区（占画面宽比例）
FULL_SCALE_X = 0.22      # 偏离中性多少算满速
JUMP_DY = 0.10           # 头部相对中性抬高多少触发动作（占画面高比例）
MOUTH_OPEN_THRESHOLD = 0.045   # 张嘴触发（MediaPipe 后端）

# 人脸框合理性筛选（见 tracker._plausible_face）。
# 这是"没识别到头却在乱动"的第一道防线：假阳性（墙上的图案、反光、抱枕）
# 的中心经常贴边，归一化后 cx 直接打到 0/1 → 角色瞬间被甩到最边上。
# 筛选宁可偶尔漏掉一个真脸 —— 漏检走的是冻结/归零逻辑，是安全的失败方向。
FACE_MIN_REL = 0.055     # 框的最小边占画面比例，更小的多属背景纹理
FACE_MAX_AREA = 0.55     # 框面积占画面比例上限（人脸不可能占满画面）
