# =========================================================================== #
# 识别质量评估与降级
# --------------------------------------------------------------------------- #
# 前面所有机制回答的都是"这一帧怎么算"，但没回答"**这一帧可不可信**"。
# 现实里有些情况是不应该硬扛的：坐得太远（脸只有几十像素，1px 抖动就是
# 百分之几的控制量）、关键点持续退化（一直侧着脸）、画面本身就是背光的。
#
# 这里把可信度显式算出来并分级，做两件事：
#   1) 给 UI 一个**具体可做**的提示（"坐近一点" 而不是笼统的"未识别"）；
#   2) 质量很差时**不再接受新的动作键触发** —— 只有这一条会改行为，
#      之所以选它：误触发跳跃是体感游戏里最糟的失败（角色自己跑了），
#      而"暂时不响应"远比"乱响应"安全。横向移动不做限制 ——
#      那会被感知成"识别变钝"，得不偿失。
#
# 状态切换必须带迟滞：提示文字如果逐帧闪，比不提示更烦人。
# =========================================================================== #
