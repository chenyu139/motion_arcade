# 因为检测本身是在 320 宽上做的，采集分辨率只影响搬运成本。
# =========================================================================== #
CAM_INDEX = 0
CAM_W = 640
CAM_H = 480
CAM_FPS = 30
DETECT_W = 320           # 人脸/手部检测都在这个缩略图上做，保证实时

# 全身骨骼 + 手部 21 点的检测频率（每 N 帧一次）。
# 头部控制由 YuNet 每帧保证实时性，而身体动作的带宽远低于 30Hz，
# 隔帧跑既能省一半开销，又不会让动作有可感知的延迟。
VISION_EVERY = 2

# 视觉帧新鲜度上限：超过这个时间没有重新推理，get_vision() 按"没有检测到"返回。
# 退避最长拉到 1/12 帧（约 0.4s），但退避只发生在"上一次就没检测到"之后，
# 所以 0.35s 对合法的保持不会误伤。
VISION_STALE_AFTER = 0.35

# =========================================================================== #
# 头部映射
# =========================================================================== #
CALIB_FRAMES = 40        # 校准采样帧数（≈1.3s @30fps）
CALIB_TRIM = 5           # 丢掉开头这几帧（人刚坐下、还在动）
CALIB_MAD_K = 2.6        # 离群剔除倍数（按中位数绝对偏差算）
                         # 真机踩过：校准时用户在看终端，24 帧里采到的 yaw 是 +0.53，
                         # 之后转回屏幕（yaw≈0）时基线偏差一直在扣，角色停在偏位不动。
                         # 加长窗口 + 剔除离群帧之后，这种"校准期间瞥了一眼别处"能被滤掉。

# --------------------------------------------------------------------------- #
# 头部映射 —— 单位一律是「人脸尺度」，不是「画面比例」
# --------------------------------------------------------------------------- #
# 这一节是"摇头/抬头经常识别错误"的根治处。
#
# 旧做法把死区与满速写成画面宽的比例（0.06 / 0.22）。问题在于**灵敏度会随坐姿
# 距离漂移**：人脸框在检测图上通常只占 0.12~0.25 的画面宽，于是
#     · 坐近（脸宽 0.25）→ 平移半个脸宽就满速，太灵、易误触
#     · 坐远（脸宽 0.12）→ 平移两个脸宽才满速，推不动、像没反应
# 用户感知到的就是"识别错误"。改成除以当帧人脸框的宽/高之后，
# 无论坐得远近、摄像头装在什么位置，手感都一致。
DEADZONE_FACE = 0.26     # 横向平移死区（单位 = 脸宽）
FULL_SCALE_FACE = 1.15   # 横向平移满速（单位 = 脸宽）
DEADZONE_FACE_Y = 0.30   # 纵向平移死区（单位 = 脸高）
FULL_SCALE_FACE_Y = 1.00 # 纵向平移满速（单位 = 脸高）

# 摇头（yaw，以"半个眼距"为单位）：**与平移融合进同一个横向控制量**。
# 只靠脸框中心位移的话，转头几乎不产生控制量（脸框中心基本不动，框还会
# 因为侧脸而收缩），用户转半天头角色不动 —— 这就是"摇头识别不到"。
#
# 阈值是**按真机实测标定**的，不是拍的：
#   鼻尖相对双眼中点的横向位移 ≈ 0.45·脸宽·sin(转头角)，
#   除以半眼距（≈0.21·脸宽）后，yaw ≈ 2.14·sin(θ)：
#       转头 12° → yaw ≈ 0.44      转头 30° → yaw ≈ 1.07
#   第一版取满速 0.50（≈12°），结果真机上轻轻一偏头轴量就打到 -0.98 ——
#   阈值太小，"太灵"和"不灵"一样会被用户感知成"识别错误"。
#   现在满速 ≈30°（舒适的自然转头幅度），死区 ≈6°（低于它的只是呼吸/说话时的微动）。
#
# 调灵敏度时**只动满速、不动死区**（用户反馈"灵敏度有点低"那轮）：
#   死区 = 噪声地板。前面算过 3px 定位抖动就有 0.22，所以 0.24 已经是安全下限，
#   再降就会把噪声放进来 —— 那就退回"头没动却在乱选"了。
#   满速 1.10 → 0.92 → 0.86 是**纯增益**：所有未饱和角度的输出统一提上去，
#   而小角度（< 8°）依然被死区挡在外面，噪声地板一点没变。
#   1.10→0.86 累计 +28%：12° 从 0.23 提到 0.32，19° 从 0.54 提到 0.77。
#   这已经是本项目的灵敏度上限了 —— 再往下调，19° 的自然转头就会打满，
#   回到第一版"轻轻一偏头就到底"的毛病（见上面那段教训）。
YAW_DEADZONE = 0.24
YAW_FULL_SCALE = 0.86

# ---- 抗抖动（这是"头没动却在乱选"的直接修复）----
# 摇头读数 = 鼻尖相对双眼中点的位移 ÷ 半眼距，而检测图只有 320 宽：
#     脸宽 ≈ 64px，眼距 ≈ 27px，**半眼距只有 13px**
# 于是鼻尖 1px 的定位抖动就等于 yaw 噪声 0.07，3px 就是 0.22（正好等于死区）。
# 这类"由小基线做差算出来的量"信噪比天生很低，必须重滤波 ——
# 平移那一路量的是 64px 尺度上的位移，同样时间常数就够了；摇头不是。
YAW_TAU = 0.20           # 摇头低通时间常数（秒）。比 HEAD_TAU 慢得多，专治这个噪声
                         # ↓ One Euro 启用后，实际由下面的「静止截止频率」换算而来

# ---- One Euro 自适应滤波（见 core/filters.py）----
# 固定时间常数有一个**无解的矛盾**：
#   · 静止时要重滤波 —— 否则噪声变成控制量（真机事故：头没动大厅却一直左右选）
#   · 移动时要轻滤波 —— 否则快速转头明显拖后路，用户感知就是"识别迟钝"
# 一个常数不可能两头都对，这是"抖"和"钝"共存的根因，调参解决不了。
# One Euro 按实时速度调节截止频率：速度为 0 → 重滤波（噪声地板不变）；
# 速度变大 → 抬高截止 → 跟手。beta=0 时严格退化为固定低通，所以是纯增益。
ONE_EURO_ENABLE = True   # 总开关；关掉即刻回到原来的固定低通行为
YAW_MIN_CUTOFF = 0.80    # 摇头静止截止（Hz）= 1/(2π·YAW_TAU) ≈ 1/(2π·0.20)
YAW_EURO_BETA = 0.55     # 摇头通道速度系数（Hz per 单位/秒）
                         # 标定依据：自然转头时 yaw 速度约 3~6/秒，beta=0.55 会把截止
                         # 从 0.8 抬到 ~2.5~4.1Hz（等效 tau 0.20→0.04s），滞后感消失；
                         # 而静止时速度项恒为 0，**噪声地板与修改前完全一致** ——
                         # 这正是它比"放宽死区"更安全的地方：只增加响应，不放进噪声。
YAW_EURO_DCUT = 1.20     # 摇头速度估计自身的低通（Hz）：抑制"抖动被当成运动"
# 速度死区（单位/秒）：**噪声也有速度，只是明显小于真实运动**。
# 低于这条线的速度一律按"静止"处理 → 截止频率恒为 min_cutoff，
# 与原固定低通严格等价，噪声地板因此一动不动。
# 取值：噪声 σ=0.18@30fps 经过 YAW_EURO_DCUT 低通后典型 |速度|≈1.9；
#       一次真实自然转头的持续速度≈4.6。取 2.5 正好卡在两者之间。
YAW_EURO_SPEED_DEAD = 2.5
AXIS_EURO_SPEED_DEAD = 0.0   # 横向输出这一路输入本身很干净，不需要速度死区
# 摇头通道的**运动学速率上限**（单位/秒）—— 放在 One Euro 之前的一层。
# 必要性：单个误检尖峰的"瞬时速度"极大，会把 One Euro 的截止频率顶到几乎直通，
# 尖峰于是绕过所有门限（实测孤立尖峰峰值从 0 涨到 0.067、两帧尖峰到 0.40）。
# 依据： yaw ≈ 2.14·sin(转头角)，实测快速转头 ~0.3 秒转 40° ≈ 4.6/秒，留余量取 5.0。
# 效果：单帧 0.95 的尖峰被削到 5.0×dt ≈ 0.17/帧 < 摇头死区 0.24 ——
#       连死区都进不去；而真实运动（速度本就在上限内）分毫无损。
YAW_MAX_RATE = 5.0
AXIS_MIN_CUTOFF = 2.12   # 横向最终输出的静止截止（Hz）= 1/(2π·HEAD_TAU)
AXIS_EURO_BETA = 0.35    # 比摇头更保守：这一路的输入本身已经很干净，
                         # 再抬高截止只会把已被死区挡住的噪声重新放进来
AXIS_EURO_DCUT = 1.50

# 死区迟滞：信号在死区边界附近时，噪声会让它反复进出，输出就是 0 / 非 0 抖。
# 已经处于"有控制"状态时用更低的退出阈值，就能钉住不抖。
AXIS_EXIT = 0.72         # 退出阈值 = 死区 × 这个系数
# 起振门限：从"静止"进入"有控制"必须持续这么久，单帧尖峰一律丢掉。
# 它同时也保护大厅 —— 一个尖峰再也不会让人跳过一格。
AXIS_ARM = 0.09          # 秒
YAW_WEIGHT = 1.00        # 摇头在横向控制里的权重
MOVE_WEIGHT = 0.85       # 平移在横向控制里的权重
                         # 两者归一化后做"软最大"融合：谁信号强就听谁的，
                         # 于是"平移能控、摇头也能控"，且不会在中间互相抵消。

# 抬头（pitch）：**以关键点算出的俯仰为主**，脸框中心的位移只作辅助。
# 只用位移时，前后移动、坐姿下滑、耸肩都会把它顶起来 —— 这是"抬头误判"的主因。
PITCH_DEADZONE = 0.09
# 同样**只动满速**（用户反馈"抬头灵敏度有点低"那轮）：0.52 → 0.43 = 纯增益 +27%，
# p_sig 0.30 处从 0.49 提到 0.62，而要按下动作键所需的实际抬头幅度从 0.27 降到 0.23。
# 死区 0.09 保持不变 —— 它挡的是**转头时俯仰读数被顶起**的耦合量：
#   实测 yaw -0.43 时 p_raw ≈ 0.32，经置信度衰减后 p_sig ≈ 0.22。
#   新映射下它对应的动作键值 0.37 < JUMP_ON(0.42)，仍留有余量、不会误触发。
PITCH_FULL_SCALE = 0.43
# 转向对俯仰读数的**置信度衰减**。
# 真机实测：转头时俯仰读数会被顶起来（yaw -0.43 时俯仰读到 +0.32，
# 逼近动作键阈值 0.42）—— 原因是 2D 人脸关键点在侧脸时会往眼线方向漂移。
#
# 这里**没有**去做"按 yaw 减掉一个耦合量"的补偿：耦合的符号和大小只能从
# 极少的实测样本里推断，猜错了会把真实的抬头信号也一起削掉（错误方向更糟）。
# 改成按转向幅度**衰减俯仰的置信度** —— 不依赖符号，且失效方向是安全的
# （"转着头的时候抬头没反应"，而不是"一转头发动机就跳"）。
#
# 斜率与上限从 0.75/0.60 提到 **0.85/0.70**：提高俯仰增益之后必须同步加强这层衰减。
# 耦合量按实测 p_raw ≈ 0.74·yaw，衰减后残余
#     p_sig ≈ 0.74·yaw·(1 - 0.85·yaw)
# 在 yaw 0.5~1.0 区间基本是平的（≈0.21~0.22），折算动作键值 ≈0.37 < JUMP_ON(0.42)。
# 旧参数在 yaw 0.85 处残余 0.25 → 键值 0.376，配上新的俯仰增益就会顶到 0.47
# **真的把动作键按下去** —— 这条由 test_yaw_pitch_decoupling 抓住（不是推测）。
PITCH_YAW_SHRINK = 0.85  # 每 1.0 个 yaw 衰减多少比例
PITCH_YAW_SHRINK_MAX = 0.70  # 最多衰减到什么程度

# 摇头方向符号。画面是镜像的，所以"往右转"预期给出正轴量。
# 保留这个开关是为了在真机上万一方向相反时能一行改回来 ——
# 符号约定依赖 landmark 的语义，无法在无头环境里用真实人脸验证。
YAW_SIGN = 1.0
# 这两个权重**只用于连续的 up / head_y（瞄准类）**。
# 动作键 jump 用的是单一来源（有姿态时只认俯仰），不能用这个融合值 ——
# 融合值里带着纵向位移，而往后靠、耸肩都会产生位移。
PITCH_WEIGHT = 0.75      # 俯仰权重
LIFT_MOVE_WEIGHT = 0.25  # 纵向位移权重（兼作姿态置信抖动时的过渡）

# 动作键（抬头）的迟滞触发：裸阈值 + 噪声 = 阈值附近疯狂抖动、一次抬头连发好几下。
JUMP_ON = 0.42           # 超过它 → 按下
JUMP_OFF = 0.22          # 低于它 → 松开（与按下阈值拉开 = 迟滞）
JUMP_MIN_HOLD = 0.08     # 最短按住时长（秒）
JUMP_MIN_GAP = 0.10      # 最短松开时长（秒）

# 中性位自适应漂移。
# 启动时只标定一次是不够的：人往后靠、身体下滑 20 秒，脸框中心就会持续偏移，
# 被当成"一直抬着头" —— 动作键常亮、角色一直在动。
# 这里在中性区附近用很慢的时间常数把基线跟着带走；持续偏置则不学
# （否则"故意保持的方向"会被学掉，游戏里反而推不动）。
NEUTRAL_ADAPT_TAU = 6.0       # 稳定后的自适应时间常数（秒）
NEUTRAL_ADAPT_TAU_FAST = 3.0  # 校准后头几秒用更快的时间常数，让基线尽快落到真实休息位
NEUTRAL_FAST_WINDOW = 8.0     # "刚校准完"持续多久（秒）
# 门限是**逐通道独立**的。真机踩过：把几个通道并在一起判，
# 俯仰偏离 0.75 时连横向基线的收敛都被卡死了 —— 明明在转头，基线却动不了。
#
# 门限的语义是"这个量还没有强到明显是操作意图"，落在门内的当作休息位吸收掉。
# 取值来自真机实测：校准期间如果把头转向别处（本次是 yaw +0.53），
# 门限必须大于这个偏差，否则角色会一直停在偏位、永远回不到中位 ——
# 那才是用户看到的"乱动"。所以横向与摇头的门限取 0.62（摇头 ≈17°）：
# 更强、明显是在操控的转向会被永久尊重（不会在几秒后被学掉）。
NEUTRAL_ADAPT_GATE = 0.62      # 横向 / 纵向平移（单位分别是脸宽 / 脸高）
NEUTRAL_ADAPT_GATE_YAW = 0.62  # 摇头（yaw 单位，≈17°）
# 俯仰门限保护的是"抬头保持"这个动作：它绝不能被当成新的休息位学掉，
# 否则游戏里就再也抬不起头了。
#
# ⚠️ 注意门限判的是**原始俯仰 p_raw**，而 JUMP_ON 是**换算之后**的动作键值，
# 两者单位不同、不能直接比。换算到同一单位才看得清关系：
#     按下动作键需要的 p_raw = PITCH_DEADZONE + JUMP_ON·(FULL_SCALE-DEADZONE)
#                            = 0.09 + 0.42×0.34 ≈ 0.23
# 也就是说"刚好能按下动作键"的那一段（0.23~0.30）现在落在门限**以内** ——
# 它没被学走，靠的是 `_adapt` 开头那条 `if self.jump: return`（按住期间冻结基线）
# 加上松开后 0.40s 的冷却。这条组合由 tools/test_head.py 的
