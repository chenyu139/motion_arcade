# =========================================================================== #
# 识别状态与失检处理（这是"没识别到头时别乱动"的核心参数）
# =========================================================================== #
# 单帧漏检非常常见：转头、眨眼间的遮挡、曝光突变、模型抖动。
# 如果直接把"这一帧没检测到"当成丢失，控制量会在每帧之间反复重启/停住，
# 表现出来就是**角色自己在乱动**。所以丢失必须是一个**带迟滞的状态**：
#
#   TRACKING  正常识别
#   HOLD      连续丢检 ≤ HOLD_AFTER：**冻结**上一次的有效输出（一点不变）
#   LOST      超过 HOLD_AFTER：轴量立即归零、动作键立即清零（不做缓慢衰减）
#
# 注意 HOLD 阶段绝不能用"衰减到 0"：那样每次漏检角色都会往中间滑一下，
# 下一帧检测回来又弹回去 —— 这正是抖动的来源。
HOLD_AFTER = 0.15        # 连续丢检不超过这个时长 → 冻结输出（约 4~5 帧 @30fps）
REACQ_STEP = 0.62        # 重新捕获那一帧，横向量的最大变化量（防假阳性把角色甩到一边）

