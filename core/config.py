# =========================================================================== #
# 摄像头
# --------------------------------------------------------------------------- #
# 分辨率不是越高越好：采集帧在采集线程里要经历 flip + resize + 两次检测，
# 全部和主线程抢 GIL。从 960×720 降回 640×480 后，头部控制的延迟明显改善，
# 因为检测本身是在 320 宽上做的，采集分辨率只影响搬运成本。
# =========================================================================== #
CAM_INDEX = 0
CAM_W = 640
CAM_H = 480
